DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'repgo_api') THEN
    CREATE ROLE repgo_api LOGIN PASSWORD 'repgo_api_2026';
  END IF;
END
$$;
GRANT CONNECT ON DATABASE repgo TO repgo_api;
GRANT USAGE ON SCHEMA public TO repgo_api;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO repgo_api;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO repgo_api;
